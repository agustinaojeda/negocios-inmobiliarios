-- Borrar tablas si existen para reiniciar el esquema correctamente
DROP TABLE IF EXISTS citas CASCADE;
DROP TABLE IF EXISTS favoritos CASCADE;
DROP TABLE IF EXISTS historial_precios CASCADE;
DROP TABLE IF EXISTS operaciones CASCADE;
DROP TABLE IF EXISTS imagenes_propiedades CASCADE;
DROP TABLE IF EXISTS propiedades CASCADE;
DROP TABLE IF EXISTS usuario_roles CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

--roles
CREATE TABLE roles (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) UNIQUE NOT NULL,
    descripcion VARCHAR(255) NOT NULL
);

--usuarios
CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    contrasena VARCHAR(255) NOT NULL,
    telefono VARCHAR(50),
    foto_perfil VARCHAR(255),
    esta_activo BOOLEAN DEFAULT TRUE,
    token_reset VARCHAR(255),
    token_expira TIMESTAMP,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

--usuario_roles
CREATE TABLE usuario_roles (
    usuario_id INTEGER UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE,
    rol_id INTEGER NOT NULL REFERENCES roles(id_rol) ON DELETE CASCADE,
    PRIMARY KEY (usuario_id, rol_id)
);

--propiedades
CREATE TABLE propiedades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    propietario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE,
    agente_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    titulo VARCHAR(255) NOT NULL,
    descripcion TEXT,
    categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('casa', 'departamento', 'ph', 'terreno', 'local')),
    moneda VARCHAR(3) NOT NULL CHECK (moneda IN ('ARS', 'USD')),
    precio DECIMAL(12, 2) NOT NULL,
    expensas DECIMAL(10, 2),
    direccion VARCHAR(255) NOT NULL,
    zona VARCHAR(100) NOT NULL,
    ambientes INTEGER NOT NULL,
    banos INTEGER NOT NULL,
    m2 INTEGER NOT NULL,
    estado_comercial VARCHAR(10) NOT NULL CHECK (estado_comercial IN ('alquiler', 'venta')),
    estado_visibilidad VARCHAR(10) NOT NULL DEFAULT 'activo' CHECK (estado_visibilidad IN ('activo', 'inactivo')),
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_baja TIMESTAMP
);

--imagenes_propiedades
CREATE TABLE imagenes_propiedades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    propiedad_id INTEGER REFERENCES propiedades(id) ON DELETE CASCADE,
    url VARCHAR(255) NOT NULL,
    orden INTEGER NOT NULL,
    es_principal BOOLEAN DEFAULT FALSE
);

--operaciones
CREATE TABLE operaciones (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    propiedad_id INTEGER REFERENCES propiedades(id) ON DELETE CASCADE,
    cliente_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE,
    moneda VARCHAR(3) NOT NULL CHECK (moneda IN ('ARS', 'USD')),
    monto_cierre DECIMAL(12, 2) NOT NULL,
    fecha_operacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_inicio_contrato DATE,
    fecha_fin_contrato DATE
);

--historial_precios
CREATE TABLE historial_precios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    propiedad_id INTEGER REFERENCES propiedades(id) ON DELETE CASCADE,
    precio_anterior DECIMAL(12, 2) NOT NULL,
    precio_nuevo DECIMAL(12, 2) NOT NULL,
    fecha_cambio TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

--favoritos
CREATE TABLE favoritos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE,
    propiedad_id INTEGER REFERENCES propiedades(id) ON DELETE CASCADE,
    fecha_agregado TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_propiedad UNIQUE (usuario_id, propiedad_id)
);

--citas
CREATE TABLE citas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquilino_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE,
    propiedad_id INTEGER REFERENCES propiedades(id) ON DELETE CASCADE,
    fecha TIMESTAMP NOT NULL,
    hora TIME NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'confirmada', 'completada', 'cancelada')),
    mensaje TEXT,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);